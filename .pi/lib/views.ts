/**
 * Deterministic Markdown views over the ledgers.
 *
 * Everything here is a pure function of the records, so `state/CONTEXT.md`,
 * `TASKS.md`, `PRS.md`, `REVIEWS.md`, and `EXPERIMENTS.md` are reproducible:
 * same ledgers in, byte-identical view out. Never edit a view by hand.
 */

import { ACTIVE_EXPERIMENT_STATUSES, projectLatest } from "./records.ts";

function cell(value: unknown): string {
	if (value === undefined || value === null) return "";
	return String(value).replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
}

function table(headers: string[], rows: unknown[][]): string[] {
	const lines = [`| ${headers.join(" | ")} |`, `|${headers.map(() => "---").join("|")}|`];
	for (const row of rows) lines.push(`| ${row.map(cell).join(" | ")} |`);
	return lines;
}

const GENERATED_BY = "<!-- generated by .pi/extensions/ledger — do not edit; edit the JSONL ledgers -->";

function byId(a: { id?: string }, b: { id?: string }): number {
	return String(a.id).localeCompare(String(b.id));
}

export function renderTasksMd(tasks: Array<Record<string, unknown>>): string {
	const rows = projectLatest(tasks as Array<{ id?: string; seq: number }>)
		.sort(byId)
		.map((t) => [t.id, t.priority, t.status, t.origin, t.title]);
	return [
		"# Tasks",
		GENERATED_BY,
		"",
		`Open: ${rows.filter((r) => !["merged", "closed", "rejected"].includes(String(r[2]))).length} / total: ${rows.length}`,
		"",
		...table(["id", "prio", "status", "origin", "title"], rows),
		"",
	].join("\n");
}

export function renderExperimentsMd(experiments: Array<Record<string, unknown>>): string {
	const rows = projectLatest(experiments as Array<{ id?: string; seq: number }>)
		.sort(byId)
		.map((e) => [e.id, e.task_id, e.status, e.attempt, e.commit_sha, e.idempotencyKey]);
	return [
		"# Experiments",
		GENERATED_BY,
		"",
		...table(["id", "task", "status", "attempt", "commit", "idempotencyKey"], rows),
		"",
	].join("\n");
}

export function renderPrsMd(prs: Array<Record<string, unknown>>): string {
	const rows = projectLatest(prs as Array<{ id?: string; seq: number }>)
		.sort(byId)
		.map((p) => [p.id, p.task_id, p.status, p.branch, p.head_sha]);
	return ["# Pull requests", GENERATED_BY, "", ...table(["id", "task", "status", "branch", "head"], rows), ""].join(
		"\n",
	);
}

export function renderReviewsMd(reviews: Array<Record<string, unknown>>): string {
	const rows = projectLatest(reviews as Array<{ id?: string; seq: number }>)
		.sort(byId)
		.map((r) => [r.id, r.pr_id, r.decision, r.actor, r.residual_risk]);
	return ["# Reviews", GENERATED_BY, "", ...table(["id", "pr", "decision", "reviewer", "residual risk"], rows), ""].join(
		"\n",
	);
}

export function renderDecisionsMd(decisions: Array<Record<string, unknown>>): string {
	const lines = ["# Decisions", GENERATED_BY, ""];
	for (const decision of projectLatest(decisions as Array<{ id?: string; seq: number }>)) {
		lines.push(`## ${cell(decision.id)} — ${cell(decision.title)}`);
		lines.push(`- context: ${cell(decision.context)}`);
		lines.push(`- decision: ${cell(decision.decision)}`);
		lines.push(`- alternatives: ${(decision.alternatives as string[]).map(cell).join("; ")}`);
		lines.push(`- consequences: ${(decision.consequences as string[]).map(cell).join("; ")}`);
		lines.push("");
	}
	return lines.join("\n");
}

export interface ContextInput {
	state: Record<string, unknown>;
	budget: Record<string, unknown>;
	tasks: Array<Record<string, unknown>>;
	experiments: Array<Record<string, unknown>>;
	reviews: Array<Record<string, unknown>>;
	prs: Array<Record<string, unknown>>;
	gates: Array<Record<string, unknown>>;
	events: Array<Record<string, unknown>>;
	maxLines?: number;
}

/** The ≤200-line summary every agent reads first. Deterministic. */
export function renderContextMd(input: ContextInput): string {
	const maxLines = input.maxLines ?? 200;
	const lines: string[] = ["# Loop context", GENERATED_BY, ""];
	const state = input.state;
	lines.push("## State", "");
	lines.push(`- state: ${cell(state.state)}${state.paused_from ? ` (paused from ${cell(state.paused_from)})` : ""}`);
	lines.push(`- run_id: ${cell(state.run_id) || "none"}`);
	lines.push(`- task: ${cell(state.task_id) || "none"}`);
	lines.push(`- pr: ${cell(state.pr_id) || "none"}`);
	lines.push(`- experiment: ${cell(state.experiment_id) || "none"} (attempt ${cell(state.attempt) || "0"})`);
	lines.push(`- next gate: ${cell(state.next_gate) || "none"}`);
	lines.push(`- reason: ${cell(state.reason) || "none"}`);
	lines.push(`- updated: ${cell(state.updated_at)} by ${cell(state.updated_by)}`);
	lines.push("");

	const budgetEntries = Object.entries(input.budget)
		.filter(([, value]) => typeof value === "number")
		.sort(([a], [b]) => a.localeCompare(b));
	lines.push("## Budget", "");
	if (budgetEntries.length === 0) lines.push("- no BUDGET.json yet (accounting arrives with S4)");
	for (const [key, value] of budgetEntries) lines.push(`- ${key}: ${cell(value)}`);
	lines.push("");

	const tasks = projectLatest(input.tasks as Array<{ id?: string; seq: number }>).sort(byId);
	const openTasks = tasks.filter((t) => !["merged", "closed", "rejected"].includes(String(t.status)));
	lines.push(`## Open tasks (${openTasks.length} of ${tasks.length})`, "");
	if (openTasks.length === 0) lines.push("- none");
	for (const task of openTasks) {
		lines.push(`- ${cell(task.id)} ${cell(task.priority)} ${cell(task.status)} ${cell(task.title)} — ${cell(task.origin)}`);
	}
	lines.push("");

	const experiments = projectLatest(input.experiments as Array<{ id?: string; seq: number }>).sort(byId);
	const active = experiments.filter((e) => (ACTIVE_EXPERIMENT_STATUSES as readonly string[]).includes(String(e.status)));
	lines.push(`## Experiments (${active.length} active of ${experiments.length})`, "");
	if (experiments.length === 0) lines.push("- none");
	for (const experiment of experiments.slice(-10)) {
		lines.push(
			`- ${cell(experiment.id)} ${cell(experiment.status)} attempt ${cell(experiment.attempt)} ` +
				`task ${cell(experiment.task_id)}`,
		);
	}
	lines.push("");

	const pendingGates = projectLatest(input.gates as Array<{ id?: string; seq: number }>).filter(
		(g) => g.status === "pending",
	);
	lines.push(`## Pending human gates (${pendingGates.length})`, "");
	if (pendingGates.length === 0) lines.push("- none");
	for (const gate of pendingGates) lines.push(`- ${cell(gate.id)} ${cell(gate.gate)}: ${cell(gate.note)}`);
	lines.push("");

	const events = [...input.events].sort((a, b) => Number(a.seq) - Number(b.seq)).slice(-10);
	lines.push("## Recent events (last 10)", "");
	for (const event of events) {
		lines.push(`- ${cell(event.ts)} ${cell(event.actor)} ${cell(event.from)}→${cell(event.to)}: ${cell(event.summary)}`);
	}
	lines.push("");

	const reviews = projectLatest(input.reviews as Array<{ id?: string; seq: number }>);
	if (reviews.length > 0) {
		lines.push(`## Recent reviews (last 5 of ${reviews.length})`, "");
		for (const review of reviews.slice(-5)) {
			lines.push(`- ${cell(review.id)} ${cell(review.pr_id)}: ${cell(review.decision)} — ${cell(review.residual_risk)}`);
		}
		lines.push("");
	}

	if (lines.length > maxLines) {
		const kept = lines.slice(0, maxLines - 1);
		kept.push(`... truncated at ${maxLines} lines; full views: .pi/state/{TASKS,EXPERIMENTS,REVIEWS,PRS}.md`);
		return `${kept.join("\n")}\n`;
	}
	return lines.join("\n").trimEnd() + "\n";
}
